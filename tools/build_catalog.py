import re
import pathlib

LOG = pathlib.Path(r"C:\Users\ahmed\McpAiChat\logs\probe_free_all.log")
OUT = pathlib.Path(r"C:\Users\ahmed\McpAiChat\tools\free_mcp_catalog.py")

text = LOG.read_text(encoding="utf-8", errors="replace")
lines = text.splitlines()

entries = []
i = 0
while i < len(lines):
    m = re.match(r"^  (.+?)\s{2,}(https?://\S+)\s*$", lines[i])
    if m and i + 1 < len(lines) and lines[i + 1].strip().startswith("OK "):
        name, url = m.group(1).strip(), m.group(2)
        status = lines[i + 1].strip()
        tools = []
        if i + 2 < len(lines) and "tools:" in lines[i + 2]:
            tools = re.findall(
                r"([A-Za-z0-9_.:-]+)", lines[i + 2].split("tools:", 1)[1]
            )
        entries.append((name, url, status, tools))
        i += 3
        continue
    i += 1

# Practical, interesting servers for a mobile AI chat client.
WANT = {
    "DeepWiki",
    "Context7",
    "CometChat Docs",
    "agent-manager Docs",
    "HuggingFace",
    "Firecrawl",
    "agentsvc.io",
    "Suprsonic",
    "Squarespace",
    "ViewportWitness",
    "Framejet",
    "localscreenshot",
    "Datakoot Weather & Geo",
    "Pushary",
    "Call Me",
    "Lium",
    "Mailcheer",
    "7Maps",
    "AI Tools Directory",
    "SkillTide",
    "Agora",
    "Agent Nexus",
    "Store API",
    "Superpowers",
    "Vextorium",
    "mcp.market",
    "ProfessionalHeadshot.io",
    "Roomvana",
    "WikiBrand",
    "Piloxa",
    "TrustyCap",
    "ADITUS Developer Portal MCP",
    "Aave",
    "Ambee",
    "Convex",
    "GoodSign",
    "Verifi",
    "ScopeLinq",
    "APEX",
    "mcp.chained",
    "Algolab MCP",
}

picked = [e for e in entries if e[0] in WANT]
picked.sort(key=lambda e: e[0].lower())

print(f"parsed {len(entries)} working servers; picked {len(picked)} for the catalog\n")

with OUT.open("w", encoding="utf-8") as fh:
    fh.write(
        '"""Curated list of free (no-auth) remote MCP servers that were verified live.\n\n'
    )
    fh.write("Every entry answered a real `initialize` + `tools/list` handshake.\n")
    fh.write("Generated by tools/probe_all_free_mcp.py — re-run it to refresh.\n")
    fh.write('"""\n\n')
    fh.write("FREE_MCP_SERVERS = [\n")
    for name, url, status, tools in picked:
        version = status.split()[1] if len(status.split()) > 1 else ""
        fh.write("    {\n")
        fh.write(f'        "name": {name!r},\n')
        fh.write(f'        "url": {url!r},\n')
        fh.write(f'        "version": {version!r},\n')
        fh.write(f'        "tools": {tools[:12]!r},\n')
        fh.write("    },\n")
    fh.write("]\n")

for name, url, status, tools in picked:
    print(f"{name:<34} {url}")
    print(f"{'':<34} {status}  →  {', '.join(tools[:6])}")
